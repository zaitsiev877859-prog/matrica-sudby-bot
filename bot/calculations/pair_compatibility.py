"""«Число Пары» для отчётов о совместимости (Направление №3), источник:
`шаблоны-эксперта/8 урок. Совместимость.pdf` (курс Макаровой, школа Ладини).

ОТКРЫТЫЙ ВОПРОС ИСТОЧНИКА: в PDF нигде не дана явная арифметика, как из
дат рождения двух партнёров получить одно число 2-22 для каждой из 6
библиотек текстов (см. 25-sovmestimost-para.md, раздел «Открытый вопрос»).
Проверено дополнительно: в bot/calculations/full_matrix.py, 18-liniya-deneg-LOM.md,
19-liniya-lyubvi-KNM.md и 20-programmy-roda-kod-seksualnosti.md формулы
совмещения двух людей тоже нет.

Формулы ниже - ГИПОТЕЗА, подтверждённая пользователем 2026-09-11 после
явного запроса (см. историю направления №3 в сессии), а не факт из
первоисточника. Основание гипотезы: PDF подписывает блоки 1/2/4/5 как
«(точка А и Б)» и блок 6 как «(точка Д)» - по аналогии с тем, как
full_matrix.py уже строит производные точки (складывает уже готовые
точки и редуцирует тем же reduce_arcana), выбрано минимальное расширение
существующей механики, а не новая независимая формула.

Не переопределяет bot.calculations.personal_core (старая классическая
механика Я02, отклонена как источник для этого отчёта решением
пользователя 2026-09-11) и не трогает bot.calculations.full_matrix
(явно исключает совместимость из своей области).
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date

from bot.calculations.full_matrix import base_square, derived_points
from bot.calculations.reduction import reduce_arcana


def pair_number_ab(person1: date, person2: date) -> int:
    """Число Пары для блоков «Для чего встретились», «Как проявляется
    пара», «Проблемы и трудности», «Негативная карма» (все подписаны в
    PDF как «(точка А и Б)»).

    [предположение, подтверждено пользователем] = редукция(А1+Б1+А2+Б2) -
    сумма точек «День» и «Мотив» (месяц) обоих партнёров.
    Диапазон 2-22 (наблюдается для «Для чего встретились» и «Как
    проявляется пара» в источнике).
    """
    sq1 = base_square(person1)
    sq2 = base_square(person2)
    return reduce_arcana(sq1.a + sq1.b + sq2.a + sq2.b)


def pair_number_d(person1: date, person2: date) -> int:
    """Число Пары для блока «Зона комфорта» (в PDF подписан «(точка Д)»).

    [предположение, подтверждено пользователем] = редукция(Д1+Д2) - сумма
    уже готовых индивидуальных точек Д (личный «синтез»/зона комфорта).
    Диапазон в источнике 5-22 (значения 2-4 в PDF для этого блока
    отсутствуют - GAP первоисточника, не наша ошибка).
    """
    sq1 = base_square(person1)
    sq2 = base_square(person2)
    return reduce_arcana(sq1.d + sq2.d)


def pair_number_m(person1: date, person2: date) -> int:
    """Число Пары для блока «Для финансового благополучия (линия КНМОЛ)».

    [предположение с ПОНИЖЕННОЙ уверенностью, подтверждено пользователем] =
    редукция(М1+М2) - сумма общей точки М (пересечение денежной линии ЛОМ
    и линии любви КНМ у каждого партнёра, см. 18-liniya-deneg-LOM.md,
    19-liniya-lyubvi-KNM.md). Основание: PDF отдельно предупреждает «1 и 2
    в этой точке не бывает» для индивидуальных точек К/Л/М/Н/О - и в блоке
    КНМОЛ для пары в источнике действительно нет текста на значение 2, что
    структурно совпадает с этим предупреждением (в отличие от блоков на
    основе А+Б, где 2 в принципе достижимо).
    """
    sq1 = base_square(person1)
    sq2 = base_square(person2)
    m1 = derived_points(sq1).m
    m2 = derived_points(sq2).m
    return reduce_arcana(m1 + m2)


@dataclass(frozen=True)
class PairNumbers:
    ab: int  # для чего встретились / как проявляется / проблемы / негативная карма
    d: int  # зона комфорта
    m: int  # финансовое благополучие (КНМОЛ)


def pair_numbers(person1: date, person2: date) -> PairNumbers:
    return PairNumbers(
        ab=pair_number_ab(person1, person2),
        d=pair_number_d(person1, person2),
        m=pair_number_m(person1, person2),
    )
